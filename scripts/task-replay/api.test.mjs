import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createFixtureClient, normalizeUsage, assistMemory, assistHandoff, decisionsBody } from './api.mjs';
const limits = { maxRequests: 2, maxInputBytes: 10000, requestTimeoutMs: 1000 };
const usage = { input_tokens: 100, output_tokens: 8, input_tokens_details: { cached_tokens: 40 } };
test('Responses is stateless, preserves reasoning configuration, bounded requests, no redirects or retries', async () => {
    const requests = [], events = [], budget = { used: 0 };
    const c = createFixtureClient({ limits, budget, onCall: e => events.push(e), fetchImpl: async (url, o) => { requests.push([url, o]); return new Response(JSON.stringify({ status: 'completed', model: 'fixture', service_tier: 'default', output: [], usage }), { status: 200 }); } });
    const args = { model: 'fixture', effort: 'high', maxOutputTokens: 128, instructions: 'fixture', input: [], tools: [] };
    await c.response(args);
    await c.response(args);
    await assert.rejects(c.response(args), /request_limit/);
    assert.equal(requests.length, 2);
    assert.equal(events.length, 4);
    assert.equal(events[0].phase, 'started');
    assert.equal(events[0].usage.inputTokens, null);
    assert.equal(events[1].usage.cachedInputTokens, 40);
    const body = JSON.parse(requests[0][1].body);
    assert.equal(body.store, false);
    assert.equal(body.service_tier, 'default');
    assert.equal(events[1].returnedModel, 'fixture');
    assert.equal(events[1].serviceTier, 'default');
    assert.deepEqual(body.include, ['reasoning.encrypted_content']);
    assert.equal(requests[0][1].redirect, 'error');
    assert.equal(requests[0][0], 'fixture:///responses');
    assert.equal(requests[0][1].headers.Authorization, undefined);
});
test('network outcome and missing usage stay unknown; no implicit paid retry', async () => {
    const events = [];
    let count = 0;
    const c = createFixtureClient({ limits, onCall: e => events.push(e), fetchImpl: async () => { count++; throw Error('secret transport detail'); } });
    await assert.rejects(c.response({ model: 'fixture', input: [], tools: [] }), /^Error: api_transport_unknown$/);
    assert.equal(count, 1);
    assert.equal(events.at(-1).usage.inputTokens, null);
    assert.equal(events.at(-1).status, 'unknown');
    assert.ok(!JSON.stringify(events).includes('secret'));
    assert.equal(normalizeUsage({ input_tokens: 10, output_tokens: 0 }).cachedInputTokens, null);
    assert.equal(normalizeUsage({ input_tokens: 10, output_tokens: 0, input_tokens_details: { cached_tokens: 0 } }).cacheWriteTokens, null);
    assert.equal(normalizeUsage({ input_tokens: 10, output_tokens: 0, input_tokens_details: { cached_tokens: 0, cache_write_tokens: 0 } }).cacheWriteTokens, 0);
});
test('offline client has no default network transport and rejects the real fetch function', () => {
    assert.throws(() => createFixtureClient({ limits }), /offline_transport_required/);
    assert.throws(() => createFixtureClient({ limits, fetchImpl: globalThis.fetch }), /offline_transport_required/);
});
test('bounded body and response protect local state before accepting output', async () => {
    let calls = 0;
    const c = createFixtureClient({ limits, onCall: () => { }, fetchImpl: async () => { calls++; return new Response('x'.repeat(2097153)); } });
    await assert.rejects(c.decisions({ model: 'fixture', input: 'x'.repeat(10001) }), /input_limit/);
    assert.equal(calls, 0);
    await assert.rejects(c.decisions({ model: 'fixture' }), /response_limit/);
    assert.equal(calls, 1);
});
test('shared contract and conservative policy keep conditional/null records fixed', async () => {
    const contract = JSON.parse(await fs.readFile(new URL('./decisions-contract.fixture.json', import.meta.url), 'utf8'));
    const rows = Array.from({ length: 4 }, (_, i) => ({ id: String(i), title: 'rule', text: 'text', kind: 'decision', authority: 'user_confirmed', conditions: i === 1 ? ['only offline'] : [] }));
    let calls = 0;
    const client = { decisions: async (body) => { calls++; assert.equal(body.input[0].content[0].data.candidates.length, 3); return { model: contract.model, answers: body.questions.map(q => q.type === 'predicate' ? { name: q.name, type: q.type, probability: Number(q.name.slice(1)) / 3 } : { name: q.name, type: q.type, choice: 'applicable', confidence: 0.8 }) }; } };
    const result = await assistMemory({ client, contract, query: 'query', records: rows });
    assert.deepEqual(result.records.map(r => r.id), ['3', '1', '2', '0']);
    assert.equal(result.records[1], rows[1]);
    assert.equal(calls, 1);
    const same = await assistHandoff({ client, contract, source: 'same', draft: 'same' });
    assert.equal(same.status, 'skipped');
    assert.equal(calls, 1);
    await assistMemory({ client, contract, query: 'query', records: rows.slice(0, 1) });
    assert.equal(calls, 1);
    assert.equal(decisionsBody(contract, 'check_handoff', { source: 's', draft: 'd', sourceTruncated: true }).questions.length, 6);
});
